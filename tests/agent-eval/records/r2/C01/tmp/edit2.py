def sub(fn, pairs):
    p = base + fn
    s = open(p, encoding="utf-8").read()
    for a, b in pairs:
        if s.count(a) != 1:
            sys.exit(f"{fn}: not unique/missing: {a!r} ({s.count(a)})")
        s = s.replace(a, b)
    open(p, "w", encoding="utf-8").write(s)

